import { Response } from 'express';
import { NotificationModel } from '../models/Notification.js';
import { AuthenticatedRequest } from '../middleware/auth.js';
import { UserModel } from '../models/User.js';
import { isDbConnected } from '../config/db.js';
import { memoryStore } from '../models/memoryStore.js';

export class NotificationController {
  public static async list(req: AuthenticatedRequest, res: Response): Promise<void> {
    try {
      if (isDbConnected()) {
        const notifications = await NotificationModel.find({ recipient: req.user!.userId })
          .sort({ createdAt: -1 })
          .limit(50)
          .populate('analysis', 'platform aiWebsite resultCategory originalUrl');

        const unreadCount = await NotificationModel.countDocuments({
          recipient: req.user!.userId,
          readAt: { $exists: false },
        });

        res.json({ notifications, unreadCount });
      } else {
        const { memoryStore } = await import('../models/memoryStore.js');
        const list = Array.from(memoryStore.notifications.values()).filter(
          (n) => n.recipient === req.user!.userId
        );
        res.json({
          notifications: list,
          unreadCount: list.filter((n) => !n.readAt).length,
        });
      }
    } catch (err: any) {
      res.status(500).json({ error: err.message || 'Error fetching notifications.' });
    }
  }

  public static async markRead(req: AuthenticatedRequest, res: Response): Promise<void> {
    try {
      const { id } = req.params;

      if (isDbConnected()) {
        const notif = await NotificationModel.findOneAndUpdate(
          { _id: id, recipient: req.user!.userId },
          { readAt: new Date() },
          { new: true }
        );

        if (!notif) {
          res.status(404).json({ error: 'Notification not found.' });
          return;
        }

        res.json({ message: 'Marked as read.', notification: notif });
      } else {
        const notif = memoryStore.notifications.get(id);
        if (notif) notif.readAt = new Date();
        res.json({ message: 'Marked as read.', notification: notif });
      }
    } catch (err: any) {
      res.status(500).json({ error: err.message || 'Error updating notification.' });
    }
  }

  public static async testAlert(req: AuthenticatedRequest, res: Response): Promise<void> {
    try {
      if (isDbConnected()) {
        const user = await UserModel.findById(req.user!.userId);
        if (!user) {
          res.status(404).json({ error: 'User not found.' });
          return;
        }

        const notif = await NotificationModel.create({
          recipient: user._id,
          type: 'ANALYSIS_COMPLETED',
          message: 'This is a test notification generated by the user in settings.',
          channel: 'IN_APP',
          deliveryStatus: 'SENT',
          deliveredAt: new Date(),
        });

        res.json({ message: 'Test notification triggered.', notification: notif });
      } else {
        const { memoryStore } = await import('../models/memoryStore.js');
        const notif = {
          _id: 'notif_' + Date.now(),
          recipient: req.user!.userId,
          type: 'ANALYSIS_COMPLETED',
          message: 'This is a test notification generated by the user in settings.',
          channel: 'IN_APP' as const,
          deliveryStatus: 'SENT' as const,
          deliveredAt: new Date(),
          createdAt: new Date(),
          updatedAt: new Date(),
        };
        memoryStore.notifications.set(notif._id, notif);
        res.json({ message: 'Test notification triggered.', notification: notif });
      }
    } catch (err: any) {
      res.status(500).json({ error: err.message || 'Error creating test alert.' });
    }
  }
}
